import { expect, test } from "vitest";
import { plugin, PLUGIN_KEY } from "./plugin.js";
const settings = {
  baseLocale: "en",
  locales: ["en", "de"],
  modules: [],
  [PLUGIN_KEY]: { pathPattern: "./Localizable.xcstrings" },
};
const sdkCapabilities = ["bundle-description"];
const encode = (value: unknown) =>
  new TextEncoder().encode(JSON.stringify(value));
const parse = (content: Uint8Array) =>
  JSON.parse(new TextDecoder().decode(content));
const source = {
  sourceLanguage: "en",
  version: "1.0",
  strings: {
    save: {
      comment: "Button guidance",
      isCommentAutoGenerated: false,
      localizations: {
        en: { stringUnit: { state: "translated", value: "Save" } },
        de: { stringUnit: { state: "translated", value: "Speichern" } },
      },
    },
  },
};

test("catalog descriptions import, edit, clear without resurrection, and survive fresh export", async () => {
  const files = [
    {
      locale: "en",
      path: "./Localizable.xcstrings",
      content: encode(source),
      imported: true,
    },
  ];
  const imported = await plugin.importFiles!({
    settings,
    sdkCapabilities,
    files,
  });
  expect(imported.bundles[0]?.description).toBe("Button guidance");
  const rows = concrete(imported);
  rows.bundles[0]!.description = "New guidance";
  for (const existing of [files, undefined]) {
    const exported = await plugin.exportFiles!({
      settings,
      sdkCapabilities,
      ...rows,
      files: existing,
    });
    expect(parse(exported[0]!.content).strings.save.comment).toBe(
      "New guidance",
    );
    expect(
      (
        await plugin.importFiles!({
          settings,
          sdkCapabilities,
          files: exported,
        })
      ).bundles[0]?.description,
    ).toBe("New guidance");
  }
  const exported = await plugin.exportFiles!({
    settings,
    sdkCapabilities,
    ...rows,
    files,
  });
  expect(parse(exported[0]!.content).strings.save.isCommentAutoGenerated).toBe(
    false,
  );
  rows.bundles[0]!.description = null;
  const cleared = await plugin.exportFiles!({
    settings,
    sdkCapabilities,
    ...rows,
    files: exported.map((f) => ({ ...f, path: f.name, imported: true })),
  });
  expect(parse(cleared[0]!.content).strings.save).not.toHaveProperty("comment");
  expect(
    (await plugin.importFiles!({ settings, sdkCapabilities, files: cleared }))
      .bundles[0]?.description,
  ).toBe(null);
});

test("old hosts keep comment as opaque metadata", async () => {
  const files = [
    {
      locale: "en",
      path: "./Localizable.xcstrings",
      content: encode(source),
      imported: true,
    },
  ];
  const imported = await plugin.importFiles!({ settings, files });
  expect(imported.bundles[0]).not.toHaveProperty("description");
  const exported = await plugin.exportFiles!({
    settings,
    ...concrete(imported),
    files,
  });
  expect(parse(exported[0]!.content).strings.save.comment).toBe(
    "Button guidance",
  );
});
function concrete(
  imported: Awaited<ReturnType<NonNullable<typeof plugin.importFiles>>>,
) {
  const messages = imported.messages.map((message, index) => ({
    ...message,
    id: `m${index}`,
    selectors: message.selectors ?? [],
  }));
  return {
    bundles: imported.bundles.map((bundle) => ({
      ...bundle,
      id: bundle.id!,
      declarations: bundle.declarations ?? [],
    })),
    messages,
    variants: imported.variants.map((variant, index) => ({
      ...variant,
      id: `v${index}`,
      matches: variant.matches ?? [],
      pattern: variant.pattern ?? [],
      messageId: messages.find(
        (m) =>
          m.bundleId === variant.messageBundleId &&
          m.locale === variant.messageLocale,
      )!.id,
    })),
  };
}
